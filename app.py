"""
Подводные приключения — Flask-сервер
======================================
Простой сервер для запуска сайта.
Запуск:  python app.py
Открой:  http://localhost:5000
"""

from flask import Flask, send_from_directory, jsonify
import os

# Создаём приложение Flask
# static_folder и static_url_path настроены так, чтобы
# сервер отдавал файлы из той же папки, где лежит app.py
app = Flask(
    __name__,
    static_folder='.',          # Папка со статическими файлами (текущая)
    static_url_path=''          # URL-путь к статическим файлам (корень)
)

# -------------------------------------------------------------------
# Маршрут для главной страницы
# -------------------------------------------------------------------
@app.route('/')
def index():
    """Отдаём index.html при заходе на главную страницу"""
    return send_from_directory('.', 'index.html')

# -------------------------------------------------------------------
# Маршрут для content.json (явно)
# -------------------------------------------------------------------
@app.route('/content.json')
def serve_content():
    """Отдаём JSON-файл с данными сайта"""
    return send_from_directory('.', 'content.json')

# -------------------------------------------------------------------
# Маршрут для любых файлов (CSS, JS, JSON, картинки и т.д.)
# -------------------------------------------------------------------
@app.route('/<path:filename>')
def serve_static(filename):
    """Отдаём любой статический файл из корня проекта"""
    return send_from_directory('.', filename)

# -------------------------------------------------------------------
# Точка входа
# -------------------------------------------------------------------
if __name__ == '__main__':
    # Запускаем сервер
    # host='0.0.0.0' — чтобы сайт был доступен с других устройств в сети
    # port=5000 — стандартный порт Flask
    # debug=True — автоматическая перезагрузка при изменении файлов
    port = int(os.environ.get('PORT', 5000))
    app.run(
        host='0.0.0.0',
        port=port,
        debug=True
    )
